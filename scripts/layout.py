#!/usr/bin/env python3
"""
Shared site layout: the single source of truth for the top navigation and the
footer. Every page carries the same nav/footer between marker comments; running
`scripts/build_site.py` rewrites those marked regions from the constants here,
so adding or renaming a tab is a one-line edit in this file plus a rebuild.

Paths are absolute (`/pages/...`) because nginx serves this repo from the web
root, so one canonical nav is valid on every page regardless of its depth.

Imported by build_site.py (static pages) and build_blogs.py (generated posts).
"""

import re

SITE_URL = 'https://www.adamfield.org'

# Cache-busting version appended to local JS/CSS URLs. HTML is served
# must-revalidate, so bumping this makes browsers/Cloudflare fetch fresh assets
# without a manual cache purge. BUMP THIS whenever shared JS/CSS changes.
ASSET_VERSION = '3'

# Top navigation. `admin=True` marks a tab whose *private* contents are gated
# behind admin auth (Phase 3); the tab itself is still listed publicly.
NAV = [
    {'label': 'Home',        'href': '/index.html'},
    {'label': 'Blog',        'href': '/pages/blog.html'},
    {'label': 'Simulations', 'href': '/pages/sims.html'},
    {'label': 'Games',       'href': '/pages/games.html'},
    {'label': 'Courses',     'href': '/pages/courses.html'},
    {'label': 'Library',     'href': '/pages/library.html'},
    {'label': 'Resume',      'href': '/pages/resume.html'},
]

# Marker comments. build_site.py / build_blogs.py replace everything *between*
# each START/END pair. A page opts into a managed region by including the pair.
NAV_START    = '<!-- SITE-NAV:START (generated by scripts/layout.py — edit there) -->'
NAV_END      = '<!-- SITE-NAV:END -->'
FOOTER_START = '<!-- SITE-FOOTER:START (generated by scripts/layout.py — edit there) -->'
FOOTER_END   = '<!-- SITE-FOOTER:END -->'


def render_nav(active_href=None, indent='    '):
    """The canonical <nav> element. `active_href` highlights the current tab."""
    links = []
    for item in NAV:
        current = ' aria-current="page"' if item['href'] == active_href else ''
        links.append(f'{indent}    <a href="{item["href"]}"{current}>{item["label"]}</a>')
    inner = '\n'.join(links)
    return f'{indent}<nav>\n{inner}\n{indent}</nav>'


def render_footer(indent='    '):
    """The canonical <footer> element (identical on every page)."""
    return f'''{indent}<footer>
{indent}    <div class="footer-content">
{indent}        <p>Created by Adam Field</p>
{indent}        <div class="footer-socials">
{indent}            <span class="contact-label">Contact me:</span>
{indent}            <div class="social-icons">
{indent}                <a href="mailto:adfield@wpi.edu" title="Email">
{indent}                    <img src="/assets/email_logo.svg" alt="email logo">
{indent}                </a>
{indent}                <a href="https://www.linkedin.com/in/adfield/" target="_blank" title="LinkedIn">
{indent}                    <img src="/assets/linkedin_logo.svg" alt="linkedin logo">
{indent}                </a>
{indent}                <a href="https://github.com/AdamField118" target="_blank" title="GitHub">
{indent}                    <img src="/assets/github_logo.svg" alt="github logo">
{indent}                </a>
{indent}            </div>
{indent}        </div>
{indent}    </div>
{indent}</footer>
{indent}<!-- Global admin widget (persistent login button + blog editing on every page) -->
{indent}<script src="/scripts/render-markdown.js?v={ASSET_VERSION}"></script>
{indent}<script src="/scripts/admin.js?v={ASSET_VERSION}"></script>'''


def _replace_region(html, start, end, new_body):
    """Replace text between `start` and `end` markers (inclusive) with the
    markers wrapping `new_body`. Returns (html, changed:bool). No-op if the
    markers aren't both present."""
    pattern = re.compile(re.escape(start) + r'.*?' + re.escape(end), re.DOTALL)
    if not pattern.search(html):
        return html, False
    replacement = f'{start}\n{new_body}\n{_leading_ws(html, start)}{end}'
    new_html = pattern.sub(lambda _m: replacement, html, count=1)
    return new_html, new_html != html


def _leading_ws(html, marker):
    """Indentation of the line the marker sits on, so the closing marker lines
    up with the opening one."""
    idx = html.find(marker)
    line_start = html.rfind('\n', 0, idx) + 1
    return html[line_start:idx]


def sync_html(path):
    """Rewrite the nav and footer regions of a single HTML file in place.
    Returns True if the file changed."""
    with open(path, encoding='utf8') as f:
        html = f.read()

    active = _active_href_for(html)
    indent_nav    = _region_indent(html, NAV_START)
    indent_footer = _region_indent(html, FOOTER_START)

    changed = False
    html, c1 = _replace_region(html, NAV_START, NAV_END,
                               render_nav(active_href=active, indent=indent_nav))
    html, c2 = _replace_region(html, FOOTER_START, FOOTER_END,
                               render_footer(indent=indent_footer))
    changed = c1 or c2

    if changed:
        with open(path, 'w', encoding='utf8') as f:
            f.write(html)
    return changed


def _region_indent(html, marker):
    return _leading_ws(html, marker) if marker in html else '    '


def _active_href_for(html):
    """Pick the nav item matching this page's canonical URL, if declared."""
    m = re.search(r'<link rel="canonical" href="https?://[^/"]+(/[^"]*)"', html)
    if not m:
        return None
    path = m.group(1) or '/'
    if path == '/':                       # site root canonical → the Home tab
        path = '/index.html'
    if path.startswith('/pages/posts/'):        # individual blog post → Blog tab
        path = '/pages/blog.html'
    if path.startswith('/pages/simulations/'):  # a simulation → Simulations tab
        path = '/pages/sims.html'
    if path == '/pages/course.html':             # a course detail → Courses tab
        path = '/pages/courses.html'
    for item in NAV:
        if item['href'] == path:
            return item['href']
    return None
